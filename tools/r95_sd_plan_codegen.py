#!/usr/bin/env python3
"""R95: generate an immutable C transaction plan for a *host fixture*.

This connects release preparation to the existing tested QNX/POSIX txn engine.
It deliberately does NOT generate a car-installable binary or touch OEM paths.
All genuine vehicle files, launch hooks, MFi and owner callbacks remain external.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys

MARKER = '.R95_HOST_FIXTURE_ONLY'
PATTERN = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_.-]{0,95}$')
ALLOWED = {'trial', 'status', 'recover', 'restore'}


def h(data):
    return hashlib.sha256(data).hexdigest()


def check_dir(p):
    if p.is_symlink() or not p.is_dir():
        raise ValueError('not a genuine directory: ' + str(p))
    if p.stat().st_uid != os.getuid():
        raise ValueError('wrong directory owner')
    return p


def check_file(p):
    if p.is_symlink() or not p.is_file():
        raise ValueError('unsafe/missing source ' + str(p))
    st = p.stat()
    if not stat.S_ISREG(st.st_mode) or st.st_nlink != 1 or st.st_uid != os.getuid():
        raise ValueError('hardlink or foreign source ' + str(p))
    if st.st_size > 16 * 1024 * 1024:
        raise ValueError('oversized file')
    return st, h(p.read_bytes())


def literal(s):
    if not s.isascii() or any(ord(c) < 32 for c in s) or '\\' in s:
        raise ValueError('non-portable path')
    return json.dumps(s)


def make(root, out):
    root = Path(root).absolute()
    if root.name.startswith('au57x-r95-') is False or root.is_symlink():
        raise ValueError('only dedicated au57x-r95-* host fixtures are accepted')
    root = check_dir(root)
    mark = root / MARKER
    if mark.is_symlink() or not mark.is_file() or mark.read_bytes() != b'FIXTURE_ONLY\n':
        raise ValueError('missing fixture marker')
    dirs = {n: check_dir(root / n) for n in ('target', 'backup', 'payload', 'state')}
    if len({(p.stat().st_dev, p.stat().st_ino) for p in dirs.values()}) != 4:
        raise ValueError('aliased transaction directories')
    for n in ('backup', 'state'):
        if any(dirs[n].iterdir()):
            raise ValueError(n + ' must start empty')
    original = list(dirs['target'].iterdir())
    changes = list(dirs['payload'].iterdir())
    if not (1 <= len(changes) <= 32):
        raise ValueError('expected between 1 and 32 candidate files')
    names = [p.name for p in changes]
    if len(set(names)) != len(names) or set(x.name for x in original) != set(names):
        raise ValueError('target/payload names must exactly match')
    rows = []
    for name in sorted(names):
        if not PATTERN.fullmatch(name) or name in ('.', '..'):
            raise ValueError('unsafe name')
        old_st, old_sha = check_file(dirs['target'] / name)
        new_st, new_sha = check_file(dirs['payload'] / name)
        if old_st.st_uid != new_st.st_uid or old_st.st_gid != new_st.st_gid:
            raise ValueError('candidate owner mismatch')
        if (stat.S_IMODE(old_st.st_mode) & ~0o777) or (stat.S_IMODE(new_st.st_mode) & ~0o777):
            raise ValueError('special permissions not supported')
        rows.append({'name': name, 'old_sha256': old_sha, 'new_sha256': new_sha,
                     'old_mode': stat.S_IMODE(old_st.st_mode),
                     'new_mode': stat.S_IMODE(new_st.st_mode),
                     'uid': old_st.st_uid, 'gid': old_st.st_gid})
    out = Path(out).absolute()
    if out.exists() or out.is_symlink() or out.parent.is_symlink():
        raise ValueError('output exists / is not a clean location')
    if not out.parent.is_dir() or out.parent.stat().st_uid != os.getuid():
        raise ValueError('untrusted output parent')
    report = {'version': 'R95', 'scope': 'HOST_FIXTURE_ONLY', 'installable': False,
              'vehicle_verified': False, 'stock_launcher_bound': False,
              'original_mfi_verified': False, 'quiesce_callback_bound': False,
              'health_check_callback_bound': False,
              'paths': {k: str(v) for k, v in dirs.items()},
              'rows': rows,
              'warning': 'No in-car startup owner or physical media durability is verified.'}
    # Avoid C code injection. All paths are checked, encoded as C string literals.
    arr = '\n'.join('  {' + ', '.join((literal(r['name']), literal(r['old_sha256']),
                  literal(r['new_sha256']), f"0{r['old_mode']:o}", f"0{r['new_mode']:o}",
                  str(r['uid']), str(r['gid']))) + '},' for r in rows)
    src = '''/* Generated by R95 OFFLINE FIXTURE codegen. NEVER INSTALL ON A VEHICLE. */
#include "txn.h"
#include <stdio.h>
#include <string.h>
static const txn_row rows[] = {
''' + arr + '''
};
int main(int argc, char **argv) {
  if (argc != 2 || (strcmp(argv[1], "trial") && strcmp(argv[1], "recover") &&
                    strcmp(argv[1], "restore") && strcmp(argv[1], "status"))) {
    fprintf(stderr, "R95 HOST FIXTURE ONLY: trial|status|recover|restore\\n");
    return 2;
  }
  const txn_spec s = {
''' + ',\n'.join('    ' + literal(str(dirs[k])) for k in ('target','backup','payload','state')) + ''',
    rows, sizeof(rows)/sizeof(rows[0]), NULL
  };
  return txn_run(&s, argv[1]) ? 1 : 0;
}
'''
    out.mkdir(mode=0o700)
    try:
        (out / 'r95_txn_fixture.c').write_text(src, encoding='ascii')
        (out / 'R95_TRANSACTION_MANIFEST.json').write_text(json.dumps(report, indent=2) + '\n', encoding='ascii')
    except BaseException:
        for p in out.iterdir(): p.unlink()
        out.rmdir()
        raise
    return report


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', required=True)
    p.add_argument('--out', required=True)
    a = p.parse_args(argv)
    try:
        result = make(a.root, a.out)
    except (ValueError, OSError) as exc:
        print('R95 STOP: '+str(exc), file=sys.stderr)
        return 2
    print(json.dumps({'generated_rows':len(result['rows']), 'scope': result['scope']}))
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
